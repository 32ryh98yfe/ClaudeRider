// Generates cross-runtime registries from "one file per entry" directories (ADR-014).
// Output files live in gitignored generated/ folders. Client-only registries use import.meta.glob instead.
import { readdirSync, mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const REG = [
  { dir: 'packages/content/src/items', out: 'packages/content/src/generated/items.gen.ts', name: 'ITEM_DEFS' },
  { dir: 'packages/content/src/effects', out: 'packages/content/src/generated/effects.gen.ts', name: 'EFFECT_DEFS' },
  { dir: 'packages/content/src/karts', out: 'packages/content/src/generated/karts.gen.ts', name: 'KART_SPECS' },
  { dir: 'packages/content/src/characters', out: 'packages/content/src/generated/characters.gen.ts', name: 'CHARACTER_METAS' },
  { dir: 'packages/content/src/themes', out: 'packages/content/src/generated/themes.gen.ts', name: 'THEME_DATAS' },
  { dir: 'packages/content/src/challenges', out: 'packages/content/src/generated/challenges.gen.ts', name: 'CHALLENGE_DEFS' },
  { dir: 'packages/content/src/tracks', out: 'packages/content/src/generated/tracks.gen.ts', name: 'TRACK_ENTRIES' },
  { dir: 'packages/sim/src/items/behaviors', out: 'packages/sim/src/generated/item-behaviors.gen.ts', name: 'ITEM_BEHAVIORS', keyed: true },
  { dir: 'packages/sim/src/items/effect-behaviors', out: 'packages/sim/src/generated/effect-behaviors.gen.ts', name: 'EFFECT_BEHAVIORS', keyed: true },
];

let wrote = 0;
for (const r of REG) {
  const dir = join(ROOT, r.dir);
  const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.ts') && !f.startsWith('_') && !f.endsWith('.test.ts')).sort() : [];
  const outPath = join(ROOT, r.out);
  mkdirSync(dirname(outPath), { recursive: true });
  const rel = (f) => './' + relative(dirname(outPath), join(dir, f)).split('\\').join('/');
  const ids = files.map((f, i) => ({ f, v: `m${i}`, key: f.replace(/\.ts$/, '') }));
  let src = '// AUTO-GENERATED by tools/gen-registries.mjs — do not edit.\n';
  for (const x of ids) src += `import ${x.v} from '${rel(x.f)}';\n`;
  if (r.keyed) src += `export const ${r.name} = {\n${ids.map((x) => `  ${JSON.stringify(x.key)}: ${x.v},`).join('\n')}\n} as const;\n`;
  else src += `export const ${r.name} = [${ids.map((x) => x.v).join(', ')}] as const;\n`;
  const prev = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (prev !== src) { writeFileSync(outPath, src); wrote++; }
}
console.log(`gen-registries: ${REG.length} registries (${wrote} updated)`);
